import assert from 'node:assert/strict';
import { chromium } from '../node_modules/.pnpm/playwright@1.55.1/node_modules/playwright/index.mjs';
const api = 'http://127.0.0.1:5003/api/v1/local-commerce';
async function request(route, method = 'GET', body) {
  const response = await fetch(api + route, { method, headers: { 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
  assert.ok(response.ok, `${method} ${route}: ${response.status} ${await response.clone().text()}`);
  return response.json();
}
const original = await request('/state');
const id = `TEST-LOCAL-${crypto.randomUUID()}`;
const variantId = `${id}-V`;
const name = `Local bağlantı testi ${Date.now()}`;
const product = { id, name, category: 'Çay makineleri', active: true, description: 'Geçici bağlantı testi', seoTitle: name, variants: [{ id: variantId, sku: id, color: 'Test', stock: 1, image: '/assets/products/tea-maker-101-blue.webp' }] };
await request(`/products/${id}`, 'PUT', product);
let browser;
let contentTouched = false;
try {
  browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
  const context = await browser.newContext();
  const admin = await context.newPage();
  const web = await context.newPage();
  const errors = [];
  console.log('Kontrol: ürün adı, görsel, stok ve fiyat…');
  admin.on('pageerror', error => errors.push(error.message));
  web.on('pageerror', error => errors.push(error.message));
  await admin.goto('http://127.0.0.1:5173');
  await admin.getByRole('status').filter({ hasText: 'Local API bağlı' }).waitFor();
  await admin.getByRole('button', { name: 'Katalog', exact: true }).click();
  await admin.getByRole('button', { name: `${name} ürününü düzenle`, exact: true }).click();
  await admin.getByLabel('Ürün adı', { exact: true }).fill(`${name} güncel`);
  await admin.getByRole('button', { name: 'Stok ve varyant', exact: true }).click();
  await admin.getByLabel('Stok', { exact: true }).fill('17');
  await admin.getByRole('button', { name: 'Medya', exact: true }).click();
  const firstUpload = admin.waitForResponse(response => response.url().endsWith('/media') && response.request().method() === 'POST' && response.status() === 200);
  await admin.getByLabel('Görsel yükle').setInputFiles('apps/web/public/assets/banners/home-slider-1.png');
  await firstUpload;
  await admin.waitForTimeout(150);
  await admin.getByRole('button', { name: 'Kaydet ve web’i güncelle', exact: true }).click();
  await admin.getByRole('dialog').waitFor({ state: 'hidden' });
  await admin.getByRole('button', { name: 'Fiyat ve kampanyalar', exact: true }).click();
  await admin.getByRole('button', { name: `${id} fiyatını düzenle`, exact: true }).click();
  await admin.getByLabel('Fiyat (TRY)', { exact: true }).fill('3456,78');
  await admin.getByRole('button', { name: 'Fiyatı kaydet', exact: true }).click();
  await admin.getByText('Fiyat kaydedildi; local web güncelleniyor.', { exact: true }).waitFor();
  await web.goto('http://127.0.0.1:3000/urunler');
  await web.getByRole('heading', { name: `${name} güncel`, exact: true }).waitFor();
  const card = web.locator('article').filter({ has: web.getByRole('heading', { name: `${name} güncel`, exact: true }) });
  assert.match(await card.textContent(), /3.456,78/);
  assert.match(await card.textContent(), /17 adet stokta/);
  assert.match(await card.locator('img').getAttribute('src'), /local-commerce\/media/);
  await card.getByRole('link', { name: /incele/i }).click();
  await web.getByRole('heading', { name: `${name} güncel`, exact: true }).waitFor();
  assert.match(await web.locator('main').textContent(), /3.456,78/);
  console.log('Kontrol: ürün detayında güncelleme ve kalıcılık…');
  await admin.getByRole('button', { name: 'Stok ve depolar', exact: true }).click();
  await admin.getByLabel(`${id} web stoğu`).fill('0');
  await admin.getByLabel(`${id} web stoğu`).locator('..').locator('..').getByRole('button', { name: 'Stoğu kaydet' }).click();
  await web.getByText('Stokta yok', { exact: true }).waitFor();
  await admin.reload();
  await admin.getByRole('status').filter({ hasText: 'Local API bağlı' }).waitFor();
  const saved = await request('/state');
  assert.equal(saved.products.find(p => p.id === id).variants[0].stock, 0);
  assert.equal(saved.prices[variantId], 345678);
  console.log('Kontrol: banner yükleme, kayıt ve silme…');
  await admin.getByRole('button', { name: 'İçerik', exact: true }).click();
  const uploaded = admin.waitForResponse(response => response.url().endsWith('/media') && response.request().method() === 'POST' && response.status() === 200);
  await admin.locator('input[type=file]').first().setInputFiles('apps/web/public/assets/banners/home-slider-1.png');
  await uploaded;
  await admin.getByLabel('Alternatif metin', { exact: true }).fill('Local bağlantı banner testi');
  contentTouched = true;
  await admin.getByRole('button', { name: 'Kaydet ve web’i güncelle', exact: true }).click();
  await admin.getByText('İçerik kaydedildi; local web güncelleniyor.', { exact: true }).waitFor();
  await web.goto('http://127.0.0.1:3000');
  const count = original.content.slides.filter(s => s.active).length + 1;
  await web.getByRole('button', { name: `${count}. görsel`, exact: true }).waitFor();
  await web.getByRole('button', { name: `${count}. görsel`, exact: true }).click();
  await web.getByRole('img', { name: 'Local bağlantı banner testi', exact: true }).waitFor();
  await admin.getByRole('button', { name: 'Bannerı sil', exact: true }).click();
  await admin.getByRole('button', { name: 'Kaydet ve web’i güncelle', exact: true }).click();
  await web.getByRole('button', { name: `${count}. görsel`, exact: true }).waitFor({ state: 'hidden' });
  assert.deepEqual(errors, []);
  console.log('PASS: Admin → API → web: ürün adı, görsel yükleme, fiyat, stok, yenilemede kalıcılık, banner ekleme/silme ve açık sayfada otomatik güncelleme.');
} finally {
  if (browser) await browser.close();
  await request(`/products/${id}`, 'DELETE');
  if (contentTouched) await request('/content', 'PUT', original.content);
}
